"""Build the event's editable, self-contained SVG artwork.

Requires Python 3 and fontTools (python -m pip install fonttools).
Run from any directory: python scripts/generate-event-artwork.py
The application serves the committed SVGs; Python is not needed at runtime.
"""

import argparse
import base64
import io
import re
from html import escape
from pathlib import Path
from xml.etree import ElementTree

from fontTools import subset
from fontTools.ttLib import TTFont


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "public" / "images"
NAVY = "#142b45"
PAPER = "#f7f2e7"
RED = "#96483e"

# Keep the typography as text, including in the downloadable files. Each SVG
# embeds just the glyphs it uses, so fonts work in <img> and offline viewers.
FONTS = {
    "display": ("Gathering-Display-BlackItalic.woff", 900, "italic"),
    "regular": ("Gathering-Myeongjo-Regular.woff", 400, "normal"),
    "bold": ("Gathering-Myeongjo-ExtraBold.woff", 800, "normal"),
}


class Artwork:
    def __init__(self, width, height, title, description, background=PAPER):
        self.width, self.height = width, height
        self.title, self.description = title, description
        self.elements = [f'<rect width="{width}" height="{height}" fill="{background}"/>']
        self.glyphs = {name: set() for name in FONTS}

    def text(self, value, x, y, size, font="regular", fill=NAVY, anchor="start"):
        self.glyphs[font].update(value)
        self.elements.append(
            f'<text x="{x}" y="{y}" font-family="Event-{font}" '
            f'font-size="{size}" font-weight="{FONTS[font][1]}" '
            f'font-style="{FONTS[font][2]}" fill="{fill}" '
            f'text-anchor="{anchor}">{escape(value)}</text>'
        )

    def rule(self, x, y, width, color=NAVY, thickness=1):
        self.elements.append(
            f'<path d="M{x} {y}h{width}" fill="none" stroke="{color}" stroke-width="{thickness}"/>'
        )

    def write(self, name):
        styles = []
        for family, chars in self.glyphs.items():
            if not chars:
                continue
            filename, weight, style = FONTS[family]
            font = TTFont(ROOT / "public" / "fonts" / filename, recalcTimestamp=False)
            options = subset.Options()
            # Preserve original attribution and OFL metadata in each subset.
            options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]
            options.name_legacy = True
            options.name_languages = ["*"]
            subsetter = subset.Subsetter(options=options)
            subsetter.populate(text="".join(sorted(chars)))
            subsetter.subset(font)
            stream = io.BytesIO()
            font.save(stream)
            encoded = base64.b64encode(stream.getvalue()).decode("ascii")
            styles.append(
                f"@font-face{{font-family:Event-{family};font-weight:{weight};"
                f"font-style:{style};src:url(data:font/woff;base64,{encoded}) format('woff')}}"
            )
        svg = (
            '<?xml version="1.0" encoding="UTF-8"?>\n'
            '<!-- Generated by scripts/generate-event-artwork.py; embedded fonts are SIL OFL 1.1. -->\n'
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{self.width}" height="{self.height}" '
            f'viewBox="0 0 {self.width} {self.height}" role="img" aria-labelledby="title description">\n'
            f'<title id="title">{escape(self.title)}</title>\n'
            f'<desc id="description">{escape(self.description)}</desc>\n'
            f'<defs><style>{"".join(styles)}</style></defs>\n'
            + "\n".join(self.elements)
            + "\n</svg>\n"
        )
        (OUTPUT / name).write_text(svg, encoding="utf-8")
        print(f"Created {name} ({len(svg.encode('utf-8')):,} bytes)")

    def write_png(self, name):
        # This small renderer handles the three primitives used above. It reads
        # the same element layout and original fonts, rather than a second design.
        from PIL import Image, ImageDraw, ImageFont

        canvas = Image.new("RGB", (self.width, self.height))
        draw = ImageDraw.Draw(canvas)
        fonts = {}
        for markup in self.elements:
            element = ElementTree.fromstring(markup)
            if element.tag == "rect":
                draw.rectangle((0, 0, self.width, self.height), fill=element.get("fill"))
            elif element.tag == "path":
                x, y, width = map(float, re.findall(r"[\d.]+", element.get("d")))
                draw.line((x, y, x + width, y), fill=element.get("stroke"),
                          width=int(element.get("stroke-width")))
            elif element.tag == "text":
                family = element.get("font-family").removeprefix("Event-")
                size = int(element.get("font-size"))
                if (family, size) not in fonts:
                    font = TTFont(ROOT / "public" / "fonts" / FONTS[family][0])
                    font.flavor = None
                    stream = io.BytesIO()
                    font.save(stream)
                    stream.seek(0)
                    fonts[family, size] = ImageFont.truetype(stream, size)
                anchor = {"start": "ls", "end": "rs", "middle": "ms"}[element.get("text-anchor")]
                draw.text((float(element.get("x")), float(element.get("y"))), element.text,
                          font=fonts[family, size], fill=element.get("fill"), anchor=anchor)
        canvas.save(OUTPUT / name, optimize=True)
        print(f"Created {name} ({self.width} x {self.height})")


